function series(
  seed: number,
  points: number,
  stepMin: number,
  base: number,
  variance: number,
  fmt: (i: number) => string,
): TimePoint[] {
  const rnd = seededRandom(seed);
  return Array.from({ length: points }, (_, i) => ({
    t: fmt(i),
    value: Math.max(
      0,
      base + (rnd() - 0.5) * 2 * variance + Math.sin(i / (points / 6)) * variance * 0.6,
    ),
    _step: stepMin,
  }));
}

const hourFmt = (points: number) => (i: number) => {
  const d = new Date(DEMO_NOW - (points - 1 - i) * 3600_000);
  return `${String(d.getHours()).padStart(2, "0")}:00`;
};
const minFmt = (points: number) => (i: number) => {
  const d = new Date(DEMO_NOW - (points - 1 - i) * 60_000);
  return `${String(d.getHours()).padStart(2, "0")}:${String(d.getMinutes()).padStart(2, "0")}`;
};
const dayFmt = (points: number) => (i: number) => {
  const d = new Date(DEMO_NOW - (points - 1 - i) * 86400_000);
  return `${d.getMonth() + 1}/${d.getDate()}`;
};

export function requestVolumeSeries(range: "1h" | "24h" | "7d" | "30d"): TimePoint[] {
  const cfg = {
    "1h": [60, minFmt(60), 420, 90],
    "24h": [48, hourFmt(48), 9800, 2100],
    "7d": [56, hourFmt(56), 9400, 2600],
    "30d": [30, dayFmt(30), 212000, 38000],
  }[range];
  const [points, fmt, base, variance] = cfg as [number, (i: number) => string, number, number];
  const rnd = seededRandom(42 + points);
  return Array.from({ length: points }, (_, i) => {
    const total = Math.max(
      0,
      base + (rnd() - 0.5) * 2 * variance + Math.sin(i / (points / 6)) * variance * 0.6,
    );
    const failed = total * (0.004 + rnd() * 0.006);
    return {
      t: fmt(i),
      total: Math.round(total),
      succeeded: Math.round(total - failed),
      failed: Math.round(failed),
    };
  });
}

export function latencySeries(points = 48, seed = 7): TimePoint[] {
  const rnd = seededRandom(seed);
  const fmt = hourFmt(points);
  return Array.from({ length: points }, (_, i) => {
    const p50 = 34 + rnd() * 6 + Math.sin(i / 8) * 3;
    return {
      t: fmt(i),
      p50: +p50.toFixed(1),
      avg: +(p50 * 1.18 + rnd() * 2).toFixed(1),
      p95: +(p50 * 1.75 + rnd() * 8).toFixed(1),
      p99: +(p50 * 2.4 + rnd() * 14).toFixed(1),
    };
  });
}

