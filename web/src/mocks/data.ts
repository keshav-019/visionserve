export function jobEventsFor(job: InferenceJob): JobEvent[] {
  const base: JobEvent[] = [
    {
      ts: job.createdAt,
      level: "info",
      stage: "submitted",
      message: `Job ${job.id} accepted by API (request ${job.requestId})`,
    },
    {
      ts: job.createdAt,
      level: "info",
      stage: "validated",
      message: "Input validated: format ok, 4.2 MP under pixel limit",
    },
    {
      ts: job.createdAt,
      level: "info",
      stage: "queued",
      message: `Entered queue ${job.environment}-default at position 3`,
    },
  ];
  if (job.startedAt) {
    base.push(
      {
        ts: job.startedAt,
        level: "info",
        stage: "worker",
        message: "Assigned to worker wrk-euc1-0412 (ONNX Runtime CPU, 8 threads)",
      },
      {
        ts: job.startedAt,
        level: "info",
        stage: "preprocess",
        message: "Decoded and letterboxed to model input shape",
      },
      {
        ts: job.startedAt,
        level: "info",
        stage: "inference",
        message: `Inference running on ${job.modelId}@${job.modelVersion}`,
      },
    );
  }
  if (job.status === "succeeded" && job.completedAt) {
    base.push({
      ts: job.completedAt,
      level: "info",
      stage: "persisted",
      message: "Result and annotated image persisted to object storage",
    });
  }
  if (job.status === "failed") {
    base.push({
      ts: job.completedAt ?? job.createdAt,
      level: "error",
      stage: "failed",
      message: `${job.errorCode}: ${job.errorMessage}`,
    });
  }
  if (job.status === "cancelled") {
    base.push({
      ts: job.completedAt ?? job.createdAt,
      level: "warn",
      stage: "cancelled",
      message: `Cancelled by ${job.owner}`,
    });
  }
  if (job.status === "expired") {
    base.push({
      ts: job.completedAt ?? job.createdAt,
      level: "warn",
      stage: "expired",
      message: "Result expired per retention policy (7 days)",
    });
  }
  return base;
}

