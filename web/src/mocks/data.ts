/**
 * Fixed clock for the demo dataset. Anchoring to a constant (instead of
 * Date.now()) keeps SSR and client renders byte-identical — a drifting clock
 * causes hydration mismatches in relative timestamps and chart axis labels.
 */
const DEMO_NOW = Date.parse("2026-07-30T12:00:00Z");

/** ISO timestamp `h` hours ago (and `m` extra minutes). */
const ago = (h: number, m = 0) => new Date(DEMO_NOW - h * 3600_000 - m * 60_000).toISOString();
/** ISO timestamp `h` hours in the future. */
const ahead = (h: number) => new Date(DEMO_NOW + h * 3600_000).toISOString();

